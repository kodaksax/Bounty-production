#!/usr/bin/env node
/**
 * Bundles the app's pure rules (lib/web/app-rules.ts) into one dependency-free
 * ES module that Supabase Edge Functions can import:
 *
 *   supabase/functions/_shared/generated/app-rules.js
 *
 * Why a bundle: Edge Functions run on Deno, which needs explicit `.ts`
 * extensions on relative imports; the app's lib/ (Metro/Jest) has none. A
 * bundle keeps one copy of the rules — the app's — instead of a hand port.
 *
 *   node scripts/build-web-app-rules.mjs          write the file
 *   node scripts/build-web-app-rules.mjs --check  exit 1 if it is stale
 *
 * __tests__/unit/web/app-rules-bundle.test.ts runs the --check logic in CI.
 * Only modules under the allow-list below may end up in the bundle: anything
 * else (services, Supabase, React Native, app config) fails the build.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = resolve(ROOT, 'lib/web/app-rules.ts');
const OUT = resolve(ROOT, 'supabase/functions/_shared/generated/app-rules.js');

/** Pure modules the bundle may contain. Add to this list deliberately. */
export const ALLOWED_INPUTS = [
  /^lib\/web\//,
  /^lib\/my-jobs\/(build-my-jobs|featured-job|format|job-strip|manage-actions|types)\.ts$/,
  /^lib\/utils\/(bounty-lifecycle|bounty-display-status|bounty-thread-events|bounty-visibility|bounty-cover|applicant-distance|review-deadline|request-expiry|schedule-utils)\.ts$/,
  /^lib\/constants\/(fees|bounty-categories)\.ts$/,
  /^lib\/strings\/trust-safety\.ts$/,
  /^lib\/messaging\/hire-welcome\.ts$/,
  /^lib\/feature-flags\.ts$/,
];

const HEADER = `// GENERATED by scripts/build-web-app-rules.mjs from lib/web/app-rules.ts — do not edit.
// The app's own rules (lib/my-jobs, lib/utils/bounty-lifecycle, bounty-thread-events),
// bundled for Deno. Rebuild after changing any of them: node scripts/build-web-app-rules.mjs
// deno-lint-ignore-file
// @ts-nocheck
`;

export async function bundle() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    metafile: true,
    legalComments: 'none',
    absWorkingDir: ROOT,
    logLevel: 'silent',
  });
  const inputs = Object.keys(result.metafile.inputs).map((p) => relative(ROOT, resolve(ROOT, p)));
  const stray = inputs.filter((p) => !ALLOWED_INPUTS.some((re) => re.test(p)));
  if (stray.length) {
    throw new Error(`app-rules bundle pulled in modules outside the pure allow-list:\n  ${stray.join('\n  ')}`);
  }
  return { code: HEADER + result.outputFiles[0].text, inputs };
}

async function main() {
  const { code, inputs } = await bundle();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== code) {
      console.error('supabase/functions/_shared/generated/app-rules.js is stale. Run: node scripts/build-web-app-rules.mjs');
      process.exit(1);
    }
    console.log('app-rules bundle is up to date');
    return;
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, code);
  console.log(`wrote ${relative(ROOT, OUT)} from ${inputs.length} modules`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => { console.error(e.message || e); process.exit(1); });
}
