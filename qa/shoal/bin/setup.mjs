#!/usr/bin/env node
/**
 * Provision the pinned Shoal checkout that Bounty's QA layer drives.
 *
 * Why a checkout and not a dependency: Shoal is not published to npm, and adding it as a
 * git dependency of this repo would pull playwright, ws and @anthropic-ai/sdk into the
 * root workspace -- i.e. into Metro's resolution graph and the Expo install. The whole
 * point of this layer is that the production bundle never learns Shoal exists, so the
 * checkout lives OUTSIDE the repo (see shoalHome()) and is driven through its real CLI.
 *
 * Steps: clone at the pinned commit -> npm install -> npm run build -> merge Bounty's
 * personas into Shoal's persona library -> verify with Shoal's own loader.
 *
 *   node qa/shoal/bin/setup.mjs [--force] [--skip-install]
 */
import { execFileSync, execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { loadConfig, shoalHome, QA_ROOT } from './lib/env.mjs';

const argv = process.argv.slice(2);
const force = argv.includes('--force');
const skipInstall = argv.includes('--skip-install');

const config = loadConfig();
const home = shoalHome(config);
const { repo, commit } = config.shoal;

function run(cmd, args, cwd) {
  console.log('  $ ' + cmd + ' ' + args.join(' '));
  execFileSync(cmd, args, { cwd, stdio: 'inherit', shell: process.platform === 'win32' });
}

function git(args, cwd) {
  return execSync('git ' + args.join(' '), { cwd, encoding: 'utf8' }).trim();
}

console.log('\n  Bounty x Shoal setup');
console.log('  checkout: ' + home);
console.log('  pinned:   ' + commit.slice(0, 12) + ' (' + repo + ')\n');

if (force && existsSync(home)) {
  console.log('  --force: removing existing checkout');
  rmSync(home, { recursive: true, force: true });
}

if (!existsSync(join(home, '.git'))) {
  mkdirSync(dirname(home), { recursive: true });
  run('git', ['clone', repo, home]);
}

// Always re-pin: a previous run may have left a different commit checked out.
run('git', ['-C', home, 'fetch', '--all', '--tags', '--quiet']);
run('git', ['-C', home, 'checkout', '--quiet', commit]);
const head = git(['rev-parse', 'HEAD'], home);
if (head !== commit) {
  console.error('  FAIL: checkout is at ' + head + ', expected ' + commit);
  process.exit(1);
}
console.log('  ok: HEAD is the pinned commit\n');

if (!skipInstall) {
  run('npm', ['install', '--no-audit', '--no-fund'], home);
  run('npm', ['run', 'build'], home);
}

const cli = join(home, 'packages', 'core', 'dist', 'cli.js');
if (!existsSync(cli)) {
  console.error('  FAIL: ' + cli + ' missing -- the build did not produce the CLI.');
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Persona sync.
//
// Shoal loads its persona library from exactly one file inside its own package
// (packages/core/src/personas.ts -> ../personas/personas.yaml) and exposes no flag for a
// different path. So Bounty's personas are MERGED into that file, with the pristine
// upstream copy kept alongside so the merge is idempotent and reversible.
// ---------------------------------------------------------------------------
const libraryPath = join(home, 'packages', 'core', 'personas', 'personas.yaml');
const upstreamPath = join(home, 'packages', 'core', 'personas', 'personas.upstream.yaml');
const bountyPath = join(QA_ROOT, 'personas', 'bounty-personas.yaml');

if (!existsSync(upstreamPath)) {
  writeFileSync(upstreamPath, readFileSync(libraryPath, 'utf8'), 'utf8');
  console.log('  saved pristine upstream persona library');
}

const upstream = readFileSync(upstreamPath, 'utf8').replace(/\s*$/, '');
const bountyRaw = readFileSync(bountyPath, 'utf8');
const listStart = bountyRaw.indexOf('\npersonas:');
if (listStart === -1) {
  console.error('  FAIL: ' + bountyPath + ' has no top-level "personas:" key.');
  process.exit(1);
}
const bountyItems = bountyRaw.slice(bountyRaw.indexOf('\n', listStart + 1) + 1).replace(/\s*$/, '');

const merged =
  upstream +
  '\n\n  # ---- BEGIN bounty personas (generated by qa/shoal/bin/setup.mjs -- do not edit here;\n' +
  '  #      edit qa/shoal/personas/bounty-personas.yaml and re-run setup) ----\n' +
  bountyItems +
  '\n  # ---- END bounty personas ----\n';
writeFileSync(libraryPath, merged, 'utf8');

// Verify with Shoal's OWN loader rather than our own parse -- if this returns our ids,
// the swarm will genuinely be able to select them with --personas.
const loaderUrl = 'file:///' + join(home, 'packages', 'core', 'dist', 'personas.js').replace(/\\/g, '/');
const { loadPersonas } = await import(loaderUrl);
const ids = loadPersonas().map((p) => p.id);
const expected = [...bountyItems.matchAll(/^\s*-\s*id:\s*(\S+)/gm)].map((m) => m[1]);
const missing = expected.filter((id) => !ids.includes(id));
if (missing.length > 0) {
  console.error('  FAIL: Shoal did not load these Bounty personas: ' + missing.join(', '));
  process.exit(1);
}

console.log('\n  personas loaded by Shoal (' + ids.length + '):');
console.log('    upstream: ' + ids.filter((i) => !i.startsWith('bounty-')).join(', '));
console.log('    bounty:   ' + ids.filter((i) => i.startsWith('bounty-')).join(', '));

// Playwright browsers. Bounty already installs Chromium for its own Playwright suite and
// both resolve the same shared cache, so this is normally a no-op.
if (!skipInstall) {
  try {
    run('npx', ['playwright', 'install', 'chromium'], home);
  } catch {
    console.warn('  !! playwright install chromium failed -- run it manually if the swarm cannot launch.');
  }
}

console.log('\n  Setup complete. Next:');
console.log('    npm run qa:shoal:web      # terminal 1 -- serve the app under test');
console.log('    npm run qa:shoal:smoke    # terminal 2 -- prove the integration works\n');
